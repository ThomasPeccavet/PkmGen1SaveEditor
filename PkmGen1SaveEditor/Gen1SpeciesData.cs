    public static uint GetExperience(byte growthRate, byte level)
    {
        long n = level;
        long value = growthRate switch
        {
            0 => n * n * n,
            1 => 3 * n * n * n / 4 + 10 * n * n - 30,
            2 => 3 * n * n * n / 4 + 20 * n * n - 70,
            3 => 6 * n * n * n / 5 - 15 * n * n + 100 * n - 140,
            4 => 4 * n * n * n / 5,
            5 => 5 * n * n * n / 4,
            _ => n * n * n
        };

        return (uint)Math.Clamp(value, 0, 0xFFFFFF);
    }
}


